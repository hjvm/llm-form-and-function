"""Repository paths, resolved independently of the current working directory.

Every pipeline step reads and writes relative to the repository root, so scripts
and notebooks behave the same whether they are run from the root, from
``pipeline/``, or by ``run_pipeline.py``.
"""
import os
from pathlib import Path


def _find_root() -> Path:
    """Locate the repository root (the directory holding ``configs/models.json``).

    Checks the ``FORM_FUNCTION_ROOT`` environment variable first, then the source
    checkout this package was installed from (``pip install -e .``), then the
    current working directory and its parents.
    """
    candidates = []
    if os.environ.get("FORM_FUNCTION_ROOT"):
        candidates.append(Path(os.environ["FORM_FUNCTION_ROOT"]))
    candidates.append(Path(__file__).resolve().parents[2])
    cwd = Path.cwd().resolve()
    candidates.extend([cwd, *cwd.parents])
    for candidate in candidates:
        if (candidate / "configs" / "models.json").exists():
            return candidate
    raise RuntimeError(
        "Could not locate the repository root. Install the package in editable mode "
        "(pip install -e .) from a clone, or set FORM_FUNCTION_ROOT."
    )


ROOT = _find_root()

CONFIGS_DIR = ROOT / "configs"
MODEL_CONFIGS = CONFIGS_DIR / "models.json"

# Inputs (not committed; see data/README.md).
DATA_DIR = ROOT / "data"
MANCHESTER_DIR = DATA_DIR / "CHILDES" / "Manchester"
TPR_DATA_DIR = DATA_DIR / "CHILDES" / "tpr-data"

# Caches and model predictions (not committed; regenerated by the pipeline).
OUTPUT_DIR = ROOT / "output"
DISCOURSE_DIR = OUTPUT_DIR / "manchester_discourse_childes"  # Step 1: model predictions
MANCHESTER_TPR_DIR = OUTPUT_DIR / "manchester_tpr_childes"   # Step 2: TPR case metadata
TPR_DATA_OUTPUT_DIR = OUTPUT_DIR / "tpr_data_analysis"       # Step 2: other-adult corpus caches

# Committed artifacts.
RESULTS_DIR = ROOT / "results"
SITE_INVENTORY_DIR = RESULTS_DIR / "site_inventory"
FIGURES_DIR = ROOT / "figures"


def chdir_to_root() -> Path:
    """Make the repository root the working directory (used at the top of each notebook)."""
    os.chdir(ROOT)
    return ROOT
